/** 界面语言对应的文案表：中文用 zh-CN，其余一律回退英文。 */
export function fuCopyTable(locale: string): FuCopyTable {
  return locale.startsWith('zh') ? fuCopyZhCN : fuCopyEn
}

/** 把文案里的 {param} 换成参数；缺失的参数渲染为空串，与模板插值一致。 */
export function formatFuCopy(text: string, params?: FuCopyParams): string {
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? ''))
}

export function useFuCopy() {
  const { locale } = useLocale()
  const copy = computed(() => fuCopyTable(String(locale.value)))
  function t(key: FuCopyKey, params?: FuCopyParams): string {
    return formatFuCopy(copy.value[key], params)
  }
  return { copy, t }
}
